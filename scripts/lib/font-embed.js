/**
 * Build every piece needed to embed a set of faces in a docx package.
 *
 * @param {object} options
 * @param {Array<{family: string, style: string, ttfPath?: string, data?: Buffer}>}
 *        options.faces faces to embed. `style` is one of
 *        regular | bold | italic | boldItalic.
 * @param {number} [options.startRelIdNumber=1000] first numeric suffix for the
 *        generated `rIdN` values. The fontTable rels part has its own id space
 *        (it is not document.xml.rels), but a high base keeps ids obviously
 *        distinct from pandoc's when reading the XML.
 * @param {boolean} [options.randomGuids=false] mint random GUIDs instead of
 *        deriving them from content (deterministic builds are the default).
 * @param {boolean} [options.requireEditable=true] enforce Editable/Installable
 *        fsType rights.
 * @param {number} [options.fontIndexBase=1] first N in `fontN.odttf`.
 *
 * @returns {{
 *   parts: Array<{path: string, data: Buffer, guid: string, relId: string,
 *                 family: string, style: string, sourceBytes: number}>,
 *   fonts: Array<object>,
 *   fontTableEntries: string,
 *   relationships: Array<{id: string, type: string, target: string}>,
 *   fontTableRelsXml: string,
 *   contentTypeDefault: string,
 *   settingsFlags: string,
 *   totalEmbeddedBytes: number,
 *   licensing: Array<object>
 * }}
 */
function buildFontEmbedding(options = {}) {
  const {
    faces,
    startRelIdNumber = 1000,
    randomGuids = false,
    requireEditable = true,
    fontIndexBase = 1,
  } = options;

  if (!Array.isArray(faces) || faces.length === 0) {
    throw new Error('font-embed: `faces` must be a non-empty array');
  }

  // Group faces by family, preserving first-seen family order.
  const families = new Map();
  const parts = [];
  const relationships = [];
  const licensing = [];
  let relCounter = startRelIdNumber;
  let fontIndex = fontIndexBase;
  let totalEmbeddedBytes = 0;

  for (const face of faces) {
    const { family, style } = face;
    if (!family) throw new Error('font-embed: each face needs a `family`');
    if (!STYLE_ELEMENTS[style]) {
      throw new Error(
        `font-embed: unknown style ${JSON.stringify(style)} for ${family}; ` +
          `expected one of ${STYLE_ORDER.join(', ')}`
      );
    }
    const source = face.ttfPath ? path.resolve(face.ttfPath) : null;
    const data = face.data
      ? Buffer.from(face.data)
      : fs.readFileSync(source);

    const label = `${family} ${style}${source ? ` (${path.basename(source)})` : ''}`;
    const meta = readFontMetadata(data);
    const rights = assertEmbeddable(label, meta.fsType, requireEditable);
    licensing.push({
      family,
      style,
      path: source,
      fsType: meta.fsType,
      ...rights,
    });

    if (!families.has(family)) {
      families.set(family, { family, meta, styles: new Map() });
    }
    const entry = families.get(family);
    if (entry.styles.has(style)) {
      throw new Error(
        `font-embed: duplicate style "${style}" for family "${family}"`
      );
    }
    // The regular face carries the most representative metrics for <w:font>.
    if (style === 'regular') entry.meta = meta;

    const guid = makeFontGuid({
      fontData: data,
      seed: `${family}|${style}`,
      random: randomGuids,
    });
    const relId = `rId${relCounter++}`;
    const partName = `font${fontIndex++}.odttf`;
    const obfuscated = obfuscateFont(data, guid);

    const part = {
      path: `${FONTS_DIR}/${partName}`,
      data: obfuscated,
      guid,
      relId,
      family,
      style,
      sourcePath: source,
      sourceBytes: data.length,
    };
    parts.push(part);
    totalEmbeddedBytes += obfuscated.length;
    relationships.push({
      id: relId,
      type: FONT_REL_TYPE,
      target: `fonts/${partName}`, // relative to word/, the rels part's base
    });
    entry.styles.set(style, part);
  }

  // ---- word/fontTable.xml entries -----------------------------------------
  const fontElements = [];
  const fonts = [];
  for (const { family, meta, styles } of families.values()) {
    const embeds = STYLE_ORDER.filter((s) => styles.has(s)).map((s) => {
      const p = styles.get(s);
      return `    <${STYLE_ELEMENTS[s]} r:id="${p.relId}" w:fontKey="${p.guid}"/>`;
    });
    const xml =
      `  <w:font w:name="${xmlEscapeAttr(family)}">\n` +
      `    <w:panose1 w:val="${meta.panose}"/>\n` +
      `    <w:charset w:val="00"/>\n` +
      `    <w:family w:val="${meta.wordFamily}"/>\n` +
      `    <w:pitch w:val="${meta.wordPitch}"/>\n` +
      `    <w:sig w:usb0="${meta.usb0}" w:usb1="${meta.usb1}" w:usb2="${meta.usb2}"` +
      ` w:usb3="${meta.usb3}" w:csb0="${meta.csb0}" w:csb1="${meta.csb1}"/>\n` +
      embeds.join('\n') +
      `\n  </w:font>`;
    fontElements.push(xml);
    fonts.push({
      family,
      xml,
      styles: [...styles.keys()],
      metadata: meta,
    });
  }

  // ---- word/_rels/fontTable.xml.rels --------------------------------------
  const fontTableRelsXml =
    `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n` +
    `<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n` +
    relationships
      .map(
        (r) =>
          `  <Relationship Id="${r.id}" Type="${r.type}" Target="${xmlEscapeAttr(r.target)}"/>`
      )
      .join('\n') +
    `\n</Relationships>\n`;

  return {
    parts,
    fonts,
    fontTableEntries: fontElements.join('\n'),
    relationships,
    fontTableRelsXml,
    contentTypeDefault: CONTENT_TYPE_DEFAULT,
    // Word only honours embedded fonts when the document asks it to; without
    // embedTrueTypeFonts a re-save will drop word/fonts/ entirely.
    settingsFlags: '<w:embedTrueTypeFonts/><w:saveSubsetFonts w:val="false"/>',
    totalEmbeddedBytes,
    licensing,
  };
}

/**
 * Splice generated `<w:font>` elements into an existing `word/fontTable.xml`,
 * replacing any pre-existing entry for the same font name so repeated runs are
 * idempotent.
 *
 * @param {string} fontTableXml current contents of word/fontTable.xml
 * @param {string} fontEntries `fontTableEntries` from {@link buildFontEmbedding}
 * @param {string[]} [families] font names whose existing entries to drop
 * @returns {string} updated XML
 */
function injectFontTableEntries(fontTableXml, fontEntries, families = []) {
  let xml = fontTableXml;
  for (const family of families) {
    // Remove an existing <w:font w:name="Family"> ... </w:font> block.
    const re = new RegExp(
      `\\s*<w:font\\b[^>]*w:name="${family.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"[\\s\\S]*?</w:font>`,
      'g'
    );
    xml = xml.replace(re, '');
    // Also handle the self-closing degenerate form.
    const reSelf = new RegExp(
      `\\s*<w:font\\b[^>]*w:name="${family.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"[^>]*/>`,
      'g'
    );
    xml = xml.replace(reSelf, '');
  }
  const close = xml.lastIndexOf('</w:fonts>');
  if (close === -1) {
    throw new Error('font-embed: fontTable.xml has no </w:fonts> element');
  }
  return xml.slice(0, close) + fontEntries + '\n' + xml.slice(close);
}

/**
 * Ensure `word/settings.xml` carries the flags Word needs to keep the embedded
 * fonts on re-save. Idempotent.
 *
 * @param {string} settingsXml
 * @returns {string}
 */
function injectSettingsFlags(settingsXml) {
  let xml = settingsXml;
  const additions = [];
  if (!/<w:embedTrueTypeFonts\b/.test(xml)) additions.push('<w:embedTrueTypeFonts/>');
  if (!/<w:saveSubsetFonts\b/.test(xml)) {
    additions.push('<w:saveSubsetFonts w:val="false"/>');
  }
  if (!additions.length) return xml;

  // w:embedTrueTypeFonts / w:saveSubsetFonts sit early in CT_Settings; placing
  // them right after <w:settings ...> keeps schema order valid in practice, but
  // anchoring to an existing sibling is safer when one is present.
  if (/<w:embedSystemFonts\b[^>]*\/>/.test(xml)) {
    return xml.replace(
      /(<w:embedSystemFonts\b[^>]*\/>)/,
      `$1${additions.join('')}`
    );
  }
  return xml.replace(/(<w:settings\b[^>]*>)/, `$1${additions.join('')}`);
}

/**
 * Ensure `[Content_Types].xml` declares the odttf Default. Pandoc emits this on
 * its own, so this is for callers writing a package without pandoc.
 * @param {string} contentTypesXml
 * @returns {string}
 */
function injectContentTypeDefault(contentTypesXml) {
  if (/Extension="odttf"/i.test(contentTypesXml)) return contentTypesXml;
  return contentTypesXml.replace(/(<Types\b[^>]*>)/, `$1${CONTENT_TYPE_DEFAULT}`);
}

