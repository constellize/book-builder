'use strict';

/**
 * font-embed.js — DOCX font embedding (ECMA-376 Part 1, §15.2.13 "Font Part").
 *
 * WHY THIS EXISTS
 * ---------------
 * Pandoc has no `--embed-fonts` for docx and never writes `word/fonts/`. But its
 * docx writer copies certain parts of the `--reference-doc` archive through to the
 * output verbatim. Empirically (pandoc 3.8.3) the passthrough set includes:
 *
 *     word/fonts/*                    <- copied verbatim (whitelisted directory)
 *     word/media/*                    <- copied verbatim
 *     word/fontTable.xml              <- copied verbatim
 *     word/_rels/fontTable.xml.rels   <- copied verbatim
 *     word/settings.xml               <- content preserved (re-serialized)
 *
 * while arbitrary paths (e.g. `word/customJunk.bin`, `customdir/x.odttf`, or a
 * loose `word/loose.odttf`) are DROPPED. So font parts MUST live under
 * `word/fonts/` — that directory is load-bearing, not a convention.
 *
 * `[Content_Types].xml` is REGENERATED by pandoc from its own template, so any
 * Default you add to the reference doc is discarded. Fortunately pandoc's writer
 * emits the obfuscatedFont Default unconditionally, in every docx it produces:
 *
 *     <Default Extension="odttf"
 *              ContentType="application/vnd.openxmlformats-officedocument.obfuscatedFont"/>
 *
 * `contentTypeDefault` is still exported here so a caller can (a) assert that
 * declaration is present in the output and (b) stay correct if it ever has to
 * write a docx without pandoc in the loop.
 *
 * OBFUSCATION
 * -----------
 * Each font part is "obfuscated" (not encrypted — it is a trivially reversible
 * XOR whose only purpose is to stop a naive drag-out-and-install):
 *   - a GUID identifies the part; it goes in `w:fontKey` on the embed element
 *   - the GUID's 32 hex digits are read as 16 bytes, and that array is REVERSED
 *   - those 16 key bytes are XORed over the FIRST 32 bytes of the font, applied
 *     twice (key[i % 16] for i in 0..31)
 *   - every byte from offset 32 onward is left untouched
 *
 * The transform is its own inverse, so `obfuscateFont` doubles as the
 * de-obfuscator and is exported as `deobfuscateFont` for verification.
 *
 * LICENSING
 * ---------
 * Embedding is only lawful if the font permits it. `readFontMetadata` returns the
 * OS/2 `fsType` bits and `assertEmbeddable` enforces them. fsType is a bitfield
 * whose low 4 bits are mutually exclusive permission levels:
 *   0  Installable        — no restriction
 *   2  Restricted         — MUST NOT be embedded
 *   4  Preview & Print    — embed allowed, read-only documents only
 *   8  Editable           — embed allowed, document may be edited
 * plus bit 0x0100 (no subsetting) and 0x0200 (bitmap embedding only).
 *
 * @module font-embed
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

/** Relationship type URI for a font part. */
const FONT_REL_TYPE =
  'http://schemas.openxmlformats.org/officeDocument/2006/relationships/font';

/** Content type for an obfuscated font part. */
const OBFUSCATED_FONT_CONTENT_TYPE =
  'application/vnd.openxmlformats-officedocument.obfuscatedFont';

/** The `[Content_Types].xml` Default that makes `.odttf` parts legal. */
const CONTENT_TYPE_DEFAULT =
  `<Default Extension="odttf" ContentType="${OBFUSCATED_FONT_CONTENT_TYPE}"/>`;

/** Directory inside the package where font parts must live. */
const FONTS_DIR = 'word/fonts';

/** The four style slots Word understands, mapped to their fontTable elements. */
const STYLE_ELEMENTS = {
  regular: 'w:embedRegular',
  bold: 'w:embedBold',
  italic: 'w:embedItalic',
  boldItalic: 'w:embedBoldItalic',
};

const STYLE_ORDER = ['regular', 'bold', 'italic', 'boldItalic'];

// ---------------------------------------------------------------------------
// GUID / obfuscation
// ---------------------------------------------------------------------------

/**
 * Normalize a GUID to the 32 uppercase hex digits, stripping braces and hyphens.
 * @param {string} guid
 * @returns {string} 32 hex characters
 */
function normalizeGuid(guid) {
  const hex = String(guid).replace(/[{}\-\s]/g, '').toUpperCase();
  if (!/^[0-9A-F]{32}$/.test(hex)) {
    throw new Error(`font-embed: not a valid GUID: ${JSON.stringify(guid)}`);
  }
  return hex;
}

/**
 * Format 32 hex digits as a braced, hyphenated, uppercase GUID — the form Word
 * writes into `w:fontKey`.
 * @param {string} hex32
 * @returns {string} e.g. `{1F2E3D4C-5B6A-7988-9A0B-1C2D3E4F5061}`
 */
function formatGuid(hex32) {
  const h = normalizeGuid(hex32);
  return `{${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}}`;
}

/**
 * Derive the 16-byte obfuscation key from a GUID: read the hex digits as bytes
 * left-to-right, then reverse the byte array.
 * @param {string} guid
 * @returns {Buffer} 16 bytes
 */
function guidToKey(guid) {
  const hex = normalizeGuid(guid);
  return Buffer.from(hex, 'hex').reverse();
}

/**
 * Apply the ECMA-376 §15.2.13 obfuscation: XOR the reversed-GUID key over the
 * first 32 bytes of the font, key repeating every 16 bytes. Self-inverse.
 *
 * @param {Buffer} fontData raw font bytes (unmodified; a copy is returned)
 * @param {string} guid the GUID that will appear in `w:fontKey`
 * @returns {Buffer} obfuscated (or de-obfuscated) bytes
 */
function obfuscateFont(fontData, guid) {
  if (!Buffer.isBuffer(fontData)) {
    throw new TypeError('font-embed: fontData must be a Buffer');
  }
  if (fontData.length < 32) {
    throw new Error(
      `font-embed: font is only ${fontData.length} bytes; §15.2.13 requires at least 32`
    );
  }
  const key = guidToKey(guid);
  const out = Buffer.from(fontData); // copy — never mutate the caller's buffer
  for (let i = 0; i < 32; i++) {
    out[i] = out[i] ^ key[i % 16];
  }
  return out;
}

/** Alias: the obfuscation is an involution, so this is the same function. */
const deobfuscateFont = obfuscateFont;

/**
 * Produce a GUID for a font part. Deterministic by default so that rebuilding
 * the book from unchanged inputs yields a byte-identical reference doc; pass
 * `{random: true}` to mint a fresh one instead.
 *
 * @param {object} opts
 * @param {Buffer} [opts.fontData] font bytes, hashed into the GUID
 * @param {string} [opts.seed] extra seed material (e.g. `family/style`)
 * @param {boolean} [opts.random] mint a random GUID instead
 * @returns {string} braced uppercase GUID
 */
function makeFontGuid({ fontData, seed = '', random = false } = {}) {
  if (random || !fontData) {
    return formatGuid(crypto.randomBytes(16).toString('hex'));
  }
  const digest = crypto
    .createHash('sha256')
    .update(seed)
    .update(fontData)
    .digest();
  const bytes = Buffer.from(digest.subarray(0, 16));
  // Stamp RFC-4122 version 4 / variant 10x so the value is a well-formed GUID.
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  return formatGuid(bytes.toString('hex'));
}

