/**
 * Parse the sfnt table directory.
 * @param {Buffer} data
 * @returns {Map<string, {offset: number, length: number}>}
 */
function readTableDirectory(data) {
  if (data.length < 12) throw new Error('font-embed: file too short to be a font');
  const tag = data.readUInt32BE(0);
  // 0x00010000 TrueType, 'OTTO' CFF, 'true'/'typ1' legacy Mac.
  const known = [0x00010000, 0x4f54544f, 0x74727565, 0x74797031];
  if (tag === 0x74746366) {
    throw new Error('font-embed: TrueType Collections (.ttc) are not supported');
  }
  if (!known.includes(tag)) {
    throw new Error(
      `font-embed: not an sfnt font (magic 0x${tag.toString(16).padStart(8, '0')})`
    );
  }
  const numTables = data.readUInt16BE(4);
  const tables = new Map();
  for (let i = 0; i < numTables; i++) {
    const rec = 12 + i * 16;
    if (rec + 16 > data.length) break;
    const name = data.toString('latin1', rec, rec + 4);
    tables.set(name, {
      offset: data.readUInt32BE(rec + 8),
      length: data.readUInt32BE(rec + 12),
    });
  }
  return tables;
}

/**
 * Read the typographic family name (name IDs 16 then 1) from the `name` table,
 * preferring the Windows/Unicode platform.
 * @param {Buffer} data
 * @param {Map} tables
 * @returns {string|null}
 */
function readFamilyName(data, tables) {
  const t = tables.get('name');
  if (!t || t.offset + 6 > data.length) return null;
  const base = t.offset;
  const count = data.readUInt16BE(base + 2);
  const stringOffset = data.readUInt16BE(base + 4);
  const candidates = [];
  for (let i = 0; i < count; i++) {
    const rec = base + 6 + i * 12;
    if (rec + 12 > data.length) break;
    const platformId = data.readUInt16BE(rec);
    const nameId = data.readUInt16BE(rec + 6);
    if (nameId !== 1 && nameId !== 16) continue;
    const len = data.readUInt16BE(rec + 8);
    const off = data.readUInt16BE(rec + 10);
    const start = base + stringOffset + off;
    if (start + len > data.length) continue;
    const raw = data.subarray(start, start + len);
    // Platform 3 (Windows) and platform 0 (Unicode) are UTF-16BE; 1 is MacRoman.
    const value =
      platformId === 1 ? raw.toString('latin1') : raw.toString('utf16le').length
        ? Buffer.from(raw).swap16().toString('utf16le')
        : raw.toString('latin1');
    candidates.push({ nameId, platformId, value: value.replace(/\0/g, '').trim() });
  }
  if (!candidates.length) return null;
  // Prefer typographic family (16) over legacy family (1); prefer Windows.
  candidates.sort(
    (a, b) => b.nameId - a.nameId || (b.platformId === 3 ? 1 : 0) - (a.platformId === 3 ? 1 : 0)
  );
  return candidates[0].value || null;
}

/**
 * Decide whether a font is monospaced by looking at actual glyph advance widths.
 *
 * The declarative flags cannot be trusted: both Atkinson families ship with
 * `post.isFixedPitch = 0`, an all-zero PANOSE and `sFamilyClass = 0`, so the
 * monospaced Mono family is indistinguishable from the proportional Next family
 * on metadata alone. Advance widths separate them cleanly — Mono's modal width
 * covers 99.7% of non-zero-width glyphs, Next's covers 3.2%.
 *
 * Zero-width glyphs (combining marks) are excluded, and a genuinely monospaced
 * font may still carry a few double-width glyphs, hence the ratio test rather
 * than requiring a single width.
 *
 * @param {Buffer} data
 * @param {Map} tables
 * @returns {boolean|null} null when hhea/hmtx are unreadable
 */
function detectMonospaceFromMetrics(data, tables) {
  const hhea = tables.get('hhea');
  const hmtx = tables.get('hmtx');
  if (!hhea || !hmtx) return null;
  if (hhea.offset + 36 > data.length) return null;
  const numHMetrics = data.readUInt16BE(hhea.offset + 34);
  if (!numHMetrics) return null;

  const counts = new Map();
  let nonZero = 0;
  for (let i = 0; i < numHMetrics; i++) {
    const off = hmtx.offset + i * 4;
    if (off + 2 > data.length) break;
    const w = data.readUInt16BE(off);
    if (w === 0) continue; // combining marks etc.
    nonZero++;
    counts.set(w, (counts.get(w) || 0) + 1);
  }
  if (nonZero === 0) return null;
  const modal = Math.max(...counts.values());
  return modal / nonZero >= 0.8;
}

/**
 * Extract the metadata needed to write a faithful `<w:font>` entry, plus the
 * licensing bits.
 *
 * @param {Buffer|string} fontOrPath font bytes or a path
 * @returns {{
 *   familyName: string|null, fsType: number, os2Version: number|null,
 *   panose: string, usb0: string, usb1: string, usb2: string, usb3: string,
 *   csb0: string, csb1: string, isFixedPitch: boolean,
 *   wordFamily: string, wordPitch: string
 * }}
 */
function readFontMetadata(fontOrPath) {
  const data = Buffer.isBuffer(fontOrPath)
    ? fontOrPath
    : fs.readFileSync(fontOrPath);
  const tables = readTableDirectory(data);

  const hex32 = (n) => (n >>> 0).toString(16).toUpperCase().padStart(8, '0');

  let fsType = 0;
  let os2Version = null;
  let panose = '00000000000000000000';
  let usb = [0, 0, 0, 0];
  let csb = [0, 0];

  const os2 = tables.get('OS/2');
  if (os2 && os2.offset + 78 <= data.length) {
    const o = os2.offset;
    os2Version = data.readUInt16BE(o);
    fsType = data.readUInt16BE(o + 8);
    panose = data.subarray(o + 32, o + 42).toString('hex').toUpperCase();
    usb = [
      data.readUInt32BE(o + 42),
      data.readUInt32BE(o + 46),
      data.readUInt32BE(o + 50),
      data.readUInt32BE(o + 54),
    ];
    // ulCodePageRange1/2 exist only from OS/2 version 1 onward.
    if (os2Version >= 1 && o + 86 <= data.length) {
      csb = [data.readUInt32BE(o + 78), data.readUInt32BE(o + 82)];
    }
  }

  const panoseBytes = Buffer.from(panose, 'hex');

  // Monospace detection, most-trusted signal first. Declarative flags are often
  // simply absent (see detectMonospaceFromMetrics), so metrics are the fallback
  // that actually decides it for the Atkinson families.
  let isFixedPitch = false;
  const post = tables.get('post');
  if (post && post.offset + 16 <= data.length) {
    isFixedPitch = data.readUInt32BE(post.offset + 12) !== 0;
  }
  // PANOSE proportion (byte 3) == 9 means monospaced for Latin Text (family 2).
  if (!isFixedPitch && panoseBytes[0] === 2 && panoseBytes[3] === 9) {
    isFixedPitch = true;
  }
  if (!isFixedPitch) {
    const byMetrics = detectMonospaceFromMetrics(data, tables);
    if (byMetrics === true) isFixedPitch = true;
  }

  // Map to Word's w:family vocabulary (ST_FontFamily: auto | decorative |
  // modern | roman | script | swiss). This is only a substitution hint — when
  // the face is embedded Word uses the real font — so "auto" is the honest
  // answer for a font that declares no classification at all, which is exactly
  // the case here (PANOSE and sFamilyClass are both zero).
  const familyClass =
    os2 && os2.offset + 32 <= data.length ? data.readInt16BE(os2.offset + 30) >> 8 : 0;
  let wordFamily = 'auto';
  if (isFixedPitch) {
    wordFamily = 'modern';
  } else if (panoseBytes[0] === 2) {
    const serifStyle = panoseBytes[1];
    if (serifStyle >= 2 && serifStyle <= 10) wordFamily = 'roman';
    else if (serifStyle >= 11 && serifStyle <= 15) wordFamily = 'swiss';
  } else if (panoseBytes[0] === 3) {
    wordFamily = 'script';
  }
  if (wordFamily === 'auto' && familyClass) {
    // IBM font-class IDs: 1..7 are the serif classes, 8 sans, 10 script.
    if (familyClass >= 1 && familyClass <= 7) wordFamily = 'roman';
    else if (familyClass === 8) wordFamily = 'swiss';
    else if (familyClass === 10) wordFamily = 'script';
    else if (familyClass === 12) wordFamily = 'decorative';
  }

  return {
    familyName: readFamilyName(data, tables),
    fsType,
    os2Version,
    panose,
    usb0: hex32(usb[0]),
    usb1: hex32(usb[1]),
    usb2: hex32(usb[2]),
    usb3: hex32(usb[3]),
    csb0: hex32(csb[0]),
    csb1: hex32(csb[1]),
    isFixedPitch,
    wordFamily,
    wordPitch: isFixedPitch ? 'fixed' : 'variable',
  };
}

/**
 * Describe fsType embedding permissions in human terms.
 * @param {number} fsType
 * @returns {{level: string, embeddable: boolean, editable: boolean,
 *            noSubsetting: boolean, bitmapOnly: boolean, summary: string}}
 */
function describeEmbeddingRights(fsType) {
  const perm = fsType & 0x000f;
  const noSubsetting = (fsType & 0x0100) !== 0;
  const bitmapOnly = (fsType & 0x0200) !== 0;
  let level;
  let embeddable = true;
  let editable = false;
  if (perm & 0x0002) {
    level = 'Restricted License (no embedding permitted)';
    embeddable = false;
  } else if (perm & 0x0004) {
    level = 'Preview & Print embedding (read-only documents)';
  } else if (perm & 0x0008) {
    level = 'Editable embedding';
    editable = true;
  } else {
    level = 'Installable embedding (no restrictions)';
    editable = true;
  }
  return {
    level,
    embeddable,
    editable,
    noSubsetting,
    bitmapOnly,
    summary:
      `fsType=${fsType} (0x${fsType.toString(16).padStart(4, '0')}): ${level}` +
      (noSubsetting ? '; no subsetting' : '') +
      (bitmapOnly ? '; bitmap embedding only' : ''),
  };
}

/**
 * Throw unless the font permits embedding in an editable document.
 * @param {string} label identifier used in the error message
 * @param {number} fsType
 * @param {boolean} [requireEditable=true] docx files the user will edit need
 *        Editable or Installable rights; Preview&Print is not enough.
 */
function assertEmbeddable(label, fsType, requireEditable = true) {
  const rights = describeEmbeddingRights(fsType);
  if (!rights.embeddable) {
    throw new Error(
      `font-embed: ${label} forbids embedding — ${rights.summary}`
    );
  }
  if (requireEditable && !rights.editable) {
    throw new Error(
      `font-embed: ${label} allows only preview/print embedding, but the output ` +
        `is an editable document — ${rights.summary}`
    );
  }
  return rights;
}

// ---------------------------------------------------------------------------
// XML helpers
// ---------------------------------------------------------------------------

function xmlEscapeAttr(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

